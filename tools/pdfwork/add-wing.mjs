// Правый коридорчик + габариты корпуса (октябрь 2026, v6).
// v6 по правке пользователя:
//  1) главный корпус ещё ниже: высота 4000 (эт. 2–5) / 4600 (эт. 1); аудитории боковых
//     рёбер (библиотеки, 63, фудкорт) сужаются по вертикали — так и надо;
//  2) коридорчик СВЕРХУ над корпусом: узкая лента-проход центрирована на правой лестнице
//     (центр ленты = центр лестницы, x 5265), аудитории — правее ленты на всю свою длину,
//     от ленты до правого ребра корпуса (x 5765..7100).
// Идемпотентно: маркер 'V4100' в контуре 5 этажа.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const file = join(root, 'data', 'economics-building.json');
const data = JSON.parse(readFileSync(file, 'utf8'));

// === габариты ===
const Y2 = 2700;                 // низ корпуса всех этажей: 7000 x 2600 — ещё уже
const Y2_1F = 2700;

// === пристройка «правый коридорчик» (этажи 2–4), сверху ===
// Корпус x 100..7100, y 100..2700. Правое ребро ленты ПРИМЫКАЕТ к правой лестнице
// (x 5078 = левое ребро лестницы 5078..5451). Лента сужена до 700, аудитории — до 1150.
const EDGE = 5078;               // левое ребро правой лестницы
const STRIP_X0 = EDGE - 700, STRIP_X1 = EDGE;
const ROOM_X0 = STRIP_X1, ROOM_X1 = 6150; // правое ребро коридорчика = левое ребро лестничной клетки нового корпуса (стыковка)
const ROOM_CX = (ROOM_X0 + ROOM_X1) / 2;
const ROOM_W = ROOM_X1 - ROOM_X0;              // 1072
const WING_TOP = -2710;
const STAIR_CX = Math.round((STRIP_X0 + STRIP_X1) / 2); // центр ленты (для подписей)
const WING_OUTLINE = 'M100,100 H' + STRIP_X0 + ' V' + WING_TOP + ' H' + ROOM_X1 + ' V100 H7100 V' + Y2 + ' H100 Z';
const WING_REGION = [0, WING_TOP - 100, 7200, Y2 + 100];

const WING_LABELS = [
  { x: STAIR_CX, y: -1600, text: 'окна', size: 240 },
  { x: STAIR_CX, y: -1240, text: 'во двор', size: 240 }
];

function sixSlots() { // 6 комнат: y -2600..-30
  const h = 370, pitch = 440, y0 = -2600, out = [];
  for (let i = 0; i < 6; i++) out.push({ h, cy: y0 + h / 2 + i * pitch });
  return out;
}

const FLOORS = {
  2: { rooms: ['202', '203', '204', '210', '211', '212'], slots: sixSlots() },
  3: { rooms: ['303', '304', '305', '306', '307', '308'], slots: sixSlots() },
  4: { rooms: ['404', '407'], slots: [{ h: 750, cy: -2225 }, { h: 750, cy: -1175 }] }
};

// Лестницы этажей 2–4: у верхнего ребра; правая (x 5078..5451) — под лентой,
// на позиции из спецификации 4 этажа (между WC М и 63А).
const STAIRS = [
  { x: 1850, y: 300, w: 373, h: 520, label: 'лестница' },
  { x: 5078, y: 300, w: 373, h: 520, label: 'лестница' }
];

// === вторая часть кампуса: корпус за коридорчиком (такой же прямоугольник 7000x2600,
// параллельно главному; низ нового корпуса = верх ленты коридорчика, y -2710) ===
const NB_Y0 = -5310, NB_Y1 = -2710;
const NB_OUTLINE = ' M100,-5310 H7100 V-2710 H100 Z';
const NB_STAIR = { x: 6150, y: -5310, w: 900, h: 2600, label: 'лестничная клетка' }; // правое ребро во всю высоту: низ (y -2710) стыкуется с коридорчиком
const NB = (id, number, name, cx, cy, w, h) => ({ id: 'NB_' + id, number, name, type: number.startsWith('WC') ? 'wc' : 'auditorium', conf: 'stand', cx, cy, w, h });
const NB_FLOORS = {
  2: [
    NB('218', '218', 'Аудитория 218 (за коридорчиком)', 575, -4010, 950, 2600),   // левое ребро, во всю высоту
    NB('217', '217', 'Аудитория 217 (за коридорчиком)', 1640, -4860, 880, 700),  // верхний ряд
    NB('216', '216', 'Аудитория 216 (за коридорчиком)', 2620, -4860, 880, 700),
    NB('215', '215', 'Аудитория 215 (за коридорчиком)', 3600, -4860, 880, 700),
    NB('214', '214', 'Аудитория 214 (за коридорчиком)', 4580, -4860, 880, 700),
    NB('WC2F', 'WC2Ж', 'WC (Ж)', 5560, -4860, 880, 700),
    NB('219', '219', 'Аудитория 219 (за коридорчиком)', 1470, -3160, 610, 700),  // нижний ряд
    NB('220', '220', 'Аудитория 220 (за коридорчиком)', 2180, -3160, 610, 700),
    NB('221', '221', 'Аудитория 221 (за коридорчиком)', 2890, -3160, 610, 700),
    NB('222', '222', 'Аудитория 222 (за коридорчиком)', 3600, -3160, 610, 700),
    NB('223', '223', 'Аудитория 223 (за коридорчиком)', 4310, -3160, 610, 700),
    NB('224', '224', 'Аудитория 224 (за коридорчиком)', 5020, -3160, 610, 700),
    NB('225', '225', 'Аудитория 225 (за коридорчиком)', 5730, -3160, 610, 700)
  ]
  // этажи 3 и 4 нового корпуса — добавим по описанию пользователя; 1 этаж пропущен намеренно
};

const lv5 = data.levels.find(l => l.id === 5);
const alreadyShort = lv5.outline.includes('V2700');

for (const lv of data.levels) {
  // 1) корпус ещё уже — сжимаем по вертикали 1/4/5 (один раз)
  if (!alreadyShort && (lv.id === 1 || lv.id === 4 || lv.id === 5)) {
    const kk = (Y2 - 100) / (3600 - 100);
    const sy = v => Math.round(100 + (v - 100) * kk);
    lv.rooms.forEach(r => {
      if (/^WING_/.test(r.id)) return;
      r.cy = sy(r.cy);
      if (r.h > 500) r.h = Math.round(r.h * kk);
    });
    (lv.stairs || []).forEach(s => { s.y = sy(s.y); s.h = Math.round(s.h * kk); });
  }
  if (lv.id === 1) {
    lv.outline = 'M100,100 H1792 V678 H100 Z M100,678 H7100 V' + Y2_1F + ' H100 Z';
    lv.region = [0, 0, 7200, 2800];
  }
  if (lv.id === 5) {
    lv.outline = 'M100,100 H7100 V' + Y2 + ' H100 Z';
    lv.region = [0, 0, 7200, 2800];
  }
  // 2) пристройка этажей 2–4
  const plan = FLOORS[lv.id];
  if (!plan) continue;
  lv.region = WING_REGION;
  lv.outline = WING_OUTLINE;
  lv.zoneLabels = WING_LABELS;
  lv.stairs = STAIRS.map(s => ({ ...s }));
  lv.rooms = lv.rooms.filter(r => !/^(WING_|NB_)/.test(r.id));
  if (lv.id === 2 || lv.id === 3) {
    const fil = lv.rooms.find(r => r.id === 'FIL2' || r.id === 'FIL3');
    if (fil) { fil.cx = 3600; fil.w = 6800; fil.cy = 1800; fil.h = 1600; }
  }
  // вторая часть кампуса (пока только 2 этаж)
  const nb = NB_FLOORS[lv.id];
  if (nb) {
    lv.outline += NB_OUTLINE;
    lv.region = [0, NB_Y0 - 100, 7200, 2800];
    lv.stairs.push({ ...NB_STAIR });
    lv.rooms.push(...nb.map(r => ({ ...r })));
  }
  plan.rooms.forEach((num, i) => {
    lv.rooms.push({
      id: 'WING_' + num,
      number: num,
      name: 'Аудитория ' + num + ', правый коридорчик',
      type: 'auditorium',
      conf: 'stand',
      cx: ROOM_CX,
      cy: plan.slots[i].cy,
      w: ROOM_W,
      h: plan.slots[i].h
    });
  });
}

data.$schema = 'Схема данных v5: главный корпус БГУ (ул. Карла Маркса, 31), обычные этажи 1–5 (октябрь 2026). Корпус 7000 x 2600 (ещё уже). Правый коридорчик (эт. 2–4): сверху, сужен (лента 700 + аудитории 1150), правое ребро ленты примыкает к правой лестнице.';
data.notes = data.notes.filter(n => !n.startsWith('Правый коридорчик'));
data.notes.push('Правый коридорчик (октябрь 2026, v9): СВЕРХХУ над корпусом, сужен — лента-проход 700 («окна во двор»), аудитории 1150; правое ребро ленты примыкает к правой лестнице (x 5078). Состав: 2 эт. — 202–204, 210–212; 3 эт. — 303–308; 4 эт. — 404, 407. Главный корпус ещё уже: 7000 x 2600 (все этажи). На этажах 1 и 5 пристройки нет, с 1 этажа хода в неё нет.');
data.notes.push('Вторая часть кампуса (октябрь 2026, v12): корпус за коридорчиком — такой же прямоугольник 7000 x 2600, параллельно главному (низ = верх ленты коридорчика), переход по коридорчику. Лестничная клетка нового корпуса (правое ребро, во всю высоту) стыкуется с коридорчиком: правое ребро коридорчика = левое ребро лестничной клетки (x 6150). Размечен 2 этаж: левое ребро — ауд. 218 (колонна на всю высоту); верхний ряд слева направо — 217, 216, 215, 214, WC Ж; нижний ряд — 219–225. Этажи 3 и 4 — по описанию пользователя, 1 этаж пропущен намеренно.');

writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8');
